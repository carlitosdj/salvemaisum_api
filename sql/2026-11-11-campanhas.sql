-- Campanhas encontradas pelo agente: de hemocentros (viram Ações quando aprovadas) e de famílias (contato pela equipe, nunca publicadas sozinhas).
-- Criada à mão no banco de produção em 2026-11-11 (aprovada pelo usuário).

CREATE TABLE IF NOT EXISTS `campanha_sugestao` (
  `id` int NOT NULL AUTO_INCREMENT,
  `execucao_id` int DEFAULT NULL,
  `tipo` varchar(12) NOT NULL,
  `situacao` varchar(12) NOT NULL DEFAULT 'nova',
  `titulo` varchar(200) NOT NULL,
  `descricao` text,
  `hemocentro_nome` varchar(255) DEFAULT NULL,
  `bloodcenter_id` int DEFAULT NULL,
  `cidade_nome` varchar(120) DEFAULT NULL,
  `uf` varchar(2) DEFAULT NULL,
  `city_id` int DEFAULT NULL,
  `inicio` varchar(10) DEFAULT NULL,
  `fim` varchar(10) DEFAULT NULL,
  `tipos_sanguineos` varchar(60) DEFAULT NULL,
  `paciente_nome` varchar(120) DEFAULT NULL,
  `contato` text,
  `fonte_nome` varchar(160) DEFAULT NULL,
  `fonte_url` varchar(500) NOT NULL,
  `fonte_data` varchar(10) DEFAULT NULL,
  `pontos_conferir` text,
  `observacao` text,
  `acao_id` int DEFAULT NULL,
  `campaign_id` int DEFAULT NULL,
  `decidido_por` int DEFAULT NULL,
  `decidido_em` int DEFAULT NULL,
  `tokens_entrada` int NOT NULL DEFAULT 0,
  `tokens_saida` int NOT NULL DEFAULT 0,
  `buscas` int NOT NULL DEFAULT 0,
  `custo_usd` decimal(10,4) NOT NULL DEFAULT 0,
  `created_at` int NOT NULL,
  `updated_at` int NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_sugestao_situacao` (`tipo`, `situacao`),
  KEY `idx_sugestao_fonte` (`fonte_url`),
  KEY `fk_sugestao_execucao` (`execucao_id`),
  KEY `fk_sugestao_bc` (`bloodcenter_id`),
  KEY `fk_sugestao_city` (`city_id`),
  KEY `fk_sugestao_decidido` (`decidido_por`),
  CONSTRAINT `fk_sugestao_execucao` FOREIGN KEY (`execucao_id`) REFERENCES `agente_execucao` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_sugestao_bc` FOREIGN KEY (`bloodcenter_id`) REFERENCES `bloodcenter` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_sugestao_city` FOREIGN KEY (`city_id`) REFERENCES `city` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fk_sugestao_decidido` FOREIGN KEY (`decidido_por`) REFERENCES `user` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
